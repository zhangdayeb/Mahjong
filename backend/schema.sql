CREATE TABLE IF NOT EXISTS demo_accounts (
 id CHAR(36) PRIMARY KEY, name VARCHAR(32) NOT NULL,
 signature VARCHAR(160) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT '',
 balance BIGINT UNSIGNED NOT NULL DEFAULT 30000,
 coin_balance BIGINT UNSIGNED NOT NULL DEFAULT 30000,
 diamond_balance BIGINT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS demo_sessions (
 token_hash CHAR(64) PRIMARY KEY, account_id CHAR(36) NOT NULL,
 expires_at TIMESTAMP NOT NULL, INDEX(account_id),
 FOREIGN KEY(account_id) REFERENCES demo_accounts(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS demo_rounds (
 id CHAR(36) PRIMARY KEY, account_id CHAR(36) NOT NULL,
 seed BIGINT UNSIGNED NOT NULL, mode VARCHAR(24) NOT NULL, room VARCHAR(24) NOT NULL,
 currency VARCHAR(12) NOT NULL DEFAULT 'beans',
 round_order BIGINT UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE,
 start_balance BIGINT UNSIGNED NOT NULL, rules_version SMALLINT UNSIGNED NOT NULL DEFAULT 1,
 rules_data JSON NULL, result_data JSON NULL, actions JSON NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'active', delta BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(account_id,status), FOREIGN KEY(account_id) REFERENCES demo_accounts(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS demo_ledger (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, account_id CHAR(36) NOT NULL,
 type VARCHAR(12) NOT NULL, round_id CHAR(36) NULL UNIQUE,
 currency VARCHAR(12) NOT NULL DEFAULT 'shared', balance_before BIGINT UNSIGNED NOT NULL DEFAULT 0,
 amount BIGINT NOT NULL, balance_after BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(account_id) REFERENCES demo_accounts(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS demo_balance_operations (
 id CHAR(36) PRIMARY KEY, account_id CHAR(36) NOT NULL,
 kind VARCHAR(12) NOT NULL, currency VARCHAR(12) NOT NULL,
 balance_before BIGINT UNSIGNED NOT NULL, balance_after BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX(account_id,currency,created_at), FOREIGN KEY(account_id) REFERENCES demo_accounts(id)
) ENGINE=InnoDB;
