import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

// Keep the client replay engine identical to the backend's browser-safe source.
// Imports become extensionless and sources get a .ts extension. Explicitly
// equivalent iterable conversions below also avoid Creator's loose Babel
// lowering of [...Map/Set] to [].concat(Map/Set).
const projectRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const sourceRoot=path.join(projectRoot,'demo');
const targetRoot=path.join(projectRoot,'creator/assets/scripts/rules');
const seen=new Map();
const imports=/(\b(?:import|export)\s+(?:(?:[^'";]*?)\s+from\s+)?)(['"])([^'"]+)\2/g;
const under=(root,file)=>{const relative=path.relative(root,file);return relative&&!relative.startsWith('..'+path.sep)&&relative!=='..'&&!path.isAbsolute(relative);};
const iterableCompatibility={
 'hand-analysis.js':[['[...wanted]','Array.from(wanted)',1]],
 'sanguo-rules.js':[
  ['[...new Set(all.filter(isSanguoHero))]','Array.from(new Set(all.filter(isSanguoHero)))',1],
  // Spread materializes sparse Array(9) holes before map; concat does not.
  ['[...Array(9)]','Array.from(Array(9))',2],
 ],
};

async function copy(relative){
 if(seen.has(relative))return;
 const source=path.resolve(sourceRoot,relative);
 if(!under(sourceRoot,source)||path.extname(source)!=='.js')throw Error('Invalid rule dependency: '+relative);
 const original=await readFile(source,'utf8');
 seen.set(relative,{sha256:createHash('sha256').update(original).digest('hex')});
 const dependencies=[];
 let transformed=original.replace(imports,(whole,prefix,quote,specifier)=>{
  if(!specifier.startsWith('.'))throw Error('Rule engine cannot depend on external packages: '+specifier);
  const dependency=path.resolve(path.dirname(source),specifier);
  if(!under(sourceRoot,dependency)||path.extname(dependency)!=='.js')throw Error('Rule dependency is not browser-safe: '+specifier);
  dependencies.push(path.relative(sourceRoot,dependency).split(path.sep).join('/'));
  return prefix+quote+specifier.slice(0,-3)+quote;
 });
 for(const [before,after,expected]of iterableCompatibility[relative]||[]){
  const occurrences=transformed.split(before).length-1;
  if(occurrences!==expected)throw Error('Iterable compatibility source changed: '+relative+' '+before);
  transformed=transformed.split(before).join(after);
 }
 if(/\b(?:document|window|navigator|localStorage|process|require)\s*[.(\[]/.test(transformed))throw Error('Rule source has a platform dependency: '+relative);
 const target=path.resolve(targetRoot,relative.replace(/\.js$/,'.ts'));
 if(!under(targetRoot,target))throw Error('Invalid rule target');
 await mkdir(path.dirname(target),{recursive:true});
 await writeFile(target,'// @ts-nocheck\n// Generated by creator/tools/sync-rules.mjs. Edit demo/'+relative+' instead.\n'+transformed,'utf8');
 for(const dependency of dependencies)await copy(dependency);
}

await copy('practice-round.js');
await copy('live-rulebook.js');
await copy('action-result-events.js');
// The legacy client exports these pure helpers from its DOM controller. Copy
// just that exact export block; importing the complete controller would pull UI.
const controller=await readFile(path.join(sourceRoot,'table-controls.js'),'utf8');
const audioStart=controller.indexOf('export function snapshotTableAudio(');
const audioEnd=controller.indexOf('export function tableControls(',audioStart);
if(audioStart<0||audioEnd<0)throw Error('Cannot locate table audio helpers');
const audioHelpers=controller.slice(audioStart,audioEnd);
await writeFile(path.join(targetRoot,'table-audio-events.ts'),'// @ts-nocheck\n// Generated pure exports from demo/table-controls.js; do not edit.\n'+audioHelpers,'utf8');
seen.set('table-controls.js [pure audio exports]',{sha256:createHash('sha256').update(audioHelpers).digest('hex')});
console.log(JSON.stringify({entry:'assets/scripts/rules/practice-round.ts',files:[...seen].sort(([a],[b])=>a.localeCompare(b)).map(([source,value])=>({source,...value}))},null,2));
